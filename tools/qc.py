#!/usr/bin/env python3
"""Automated quality checks for every print file. Writes qc/qc-report.md.

    python3 tools/qc.py

Checks: pixel size vs. spec, real pixel resolution at print size (not DPI
metadata), transparency, art clipped at edges, semi-transparent pixels, colour
count, smallest text size at print, and contrast against each blank colour.
Blank colour hex values are APPROXIMATE screen matches, not manufacturer specs.
"""
import json
import sys
from pathlib import Path

import numpy as np
from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "tools"))
from build_art import SPECS  # noqa: E402

# Physical print-area width in inches for each spec (px / 300). Mug wrap is
# about 8.25 in around an 11oz mug.
BLANK_COLOURS = {  # approximate
    "ruined-by-chapter-twelve-tee": {"Ivory": "#F0E9DA", "Blossom": "#F4C7CD", "Orchid": "#D9C6DE"},
    "yearning-night-shift-sweatshirt": {"Sand": "#DCD0B9", "Light Pink": "#F3D3DC", "White": "#FFFFFF"},
    "yearning-morning-shift-mug": {"White mug": "#FFFFFF"},
    "contents-tote": {"Natural": "#EFE6D2"},
    "will-they-tee": {"Ivory": "#F0E9DA", "Blossom": "#F4C7CD", "Orchid": "#D9C6DE"},
    "pining-professionally-sweatshirt": {"Sand": "#DCD0B9", "Light Pink": "#F3D3DC", "White": "#FFFFFF"},
}
MIN_CAP_IN = 0.10      # smallest acceptable capital-letter height at print
MIN_CONTRAST = 4.5     # WCAG AA for normal text; used as a print legibility proxy
EDGE_MARGIN_PX = 20


def lum(rgb):
    def ch(c):
        c = c / 255
        return c / 12.92 if c <= 0.03928 else ((c + 0.055) / 1.055) ** 2.4
    r, g, b = rgb
    return 0.2126 * ch(r) + 0.7152 * ch(g) + 0.0722 * ch(b)


def contrast(a, b):
    la, lb = sorted((lum(a), lum(b)), reverse=True)
    return (la + 0.05) / (lb + 0.05)


def hex_rgb(h):
    h = h.lstrip("#")
    return tuple(int(h[i:i + 2], 16) for i in (0, 2, 4))


def check(slug):
    path = ROOT / "products" / slug / "art" / f"{slug}-print.png"
    im = Image.open(path)
    res = []

    def add(name, ok, detail):
        res.append((name, "PASS" if ok else ("WARN" if ok is None else "FAIL"), detail))

    W, H = im.size
    add("Pixel size matches spec", (W, H) == SPECS[slug], f"{W}×{H} px (spec {SPECS[slug][0]}×{SPECS[slug][1]})")
    dpi = im.info.get("dpi", (0, 0))
    eff = W / (SPECS[slug][0] / 300)
    add("Real resolution at print size", eff >= 300,
        f"{eff:.0f} px/in at {SPECS[slug][0] / 300:.2f} in wide (DPI tag {dpi[0]:.0f}; tag is not relied on)")
    add("Colour mode RGBA / sRGB", im.mode == "RGBA", im.mode)
    a = np.array(im)
    alpha = a[..., 3]
    add("Transparent background", alpha[0, 0] == 0 and (alpha == 0).mean() > 0.3,
        f"{(alpha == 0).mean() * 100:.1f}% fully transparent")
    ys, xs = np.nonzero(alpha)
    x0, x1, y0, y1 = xs.min(), xs.max(), ys.min(), ys.max()
    margin = min(x0, y0, W - 1 - x1, H - 1 - y1)
    add("Art not clipped at edges", margin >= EDGE_MARGIN_PX, f"closest art to edge: {margin} px")
    add("Art size at print", True,
        f"{(x1 - x0 + 1) / 300:.2f} × {(y1 - y0 + 1) / 300:.2f} in (bounding box)")
    semi = ((alpha > 0) & (alpha < 255)).sum() / max(1, (alpha > 0).sum())
    add("Semi-transparent pixels", semi < 0.15,
        f"{semi * 100:.1f}% of inked pixels (anti-aliased edges only; no fades/glows used)")
    opaque = a[alpha == 255][:, :3]
    cols = {tuple(c) for c in np.unique(opaque, axis=0)}
    add("Spot colours", len(cols) <= 4, f"{len(cols)} solid colours: " + ", ".join("#%02X%02X%02X" % c for c in sorted(cols)))
    texts = json.loads((path.parent / "text-sizes.json").read_text())
    smallest = min(texts, key=lambda t: t["font_px"])
    cap_in = smallest["font_px"] * 0.70 / 300
    add("Smallest text height at print", cap_in >= MIN_CAP_IN,
        f"'{smallest['text']}' ≈ {cap_in:.2f} in cap height ({smallest['font_px']} px font)")
    for name, hx in BLANK_COLOURS[slug].items():
        worst = min(contrast(c, hex_rgb(hx)) for c in cols)
        add(f"Contrast on {name} (≈{hx})", worst >= MIN_CONTRAST if worst >= 3 else False,
            f"lowest ink contrast {worst:.1f}:1")
    return res


def main():
    lines = ["# QC Report — print files", "",
             "Generated by `tools/qc.py`. Re-run after any artwork change.", "",
             "Contrast uses **approximate** blank colours; confirm against Printify's colour swatches/mockups.",
             "Specs are **UNVERIFIED** until checked in Printify (see `research/verification-needed.md`).", ""]
    fails = 0
    for slug in SPECS:
        lines += [f"## {slug}", "", "| Check | Result | Detail |", "|---|---|---|"]
        for name, status, detail in check(slug):
            fails += status == "FAIL"
            lines.append(f"| {name} | {status} | {detail} |")
        lines.append("")
    manual = ROOT / "qc" / "journal-qc.md"  # manual checks for the digital product
    if manual.exists():
        lines += ["", manual.read_text()]
    out = ROOT / "qc" / "qc-report.md"
    out.parent.mkdir(exist_ok=True)
    out.write_text("\n".join(lines))
    print("\n".join(lines))
    print(f"\nFAIL count: {fails}")


if __name__ == "__main__":
    main()
